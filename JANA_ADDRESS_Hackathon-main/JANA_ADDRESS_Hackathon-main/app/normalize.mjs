// Предварительная нормализация/токенизация слитно написанных адресов — без LLM, только правила.
//
//   "Астана12дом4подъезд191кв."  ->  "Астана 12 дом 4 подъезд 191 кв."
//   "Абая12дом5кв34"             ->  "Абая 12 дом 5 кв 34"
//   "Ул .Курильская9кв1"         ->  "Ул. Курильская 9 кв 1"
//
// Модуль ничего не знает о справочнике и не извлекает поля: он только ставит пробелы на стыках
// токенов, чтобы дальше парсер работал с привычным «раздельным» текстом. Правила намеренно
// консервативны — лучше оставить склейку, чем разрезать то, что склейкой не является:
//
//   * «12а», «55/6», «3б» не режутся — литера и дробь остаются частью номера дома;
//   * одиночное «д»/«к»/«э» не считается ключевым словом («12д» — это литера, а не «дом»);
//   * ключевое слово должно стоять целиком: «5квартал» режется, «5квази» — нет;
//   * буква→цифра режется только если слева слово из ≥2 букв («Абая12», но не «А5»).

const U = "\\p{L}";

// Ключевые слова реквизитов. Одиночные буквы сюда не входят — см. шапку файла.
const DETAIL_KEYWORDS = [
  // квартира
  "квартира", "квартал", "кв", "пәтер", "пәт", "apartment", "apt", "flat", "kv",
  // подъезд
  "подъезд", "подьезд", "подезд", "подъ", "кіреберіс", "entrance", "entr",
  // этаж
  "этаж", "эт", "қабат", "floor",
  // дом
  "дом", "үй", "house", "bldg",
  // тип улицы, который часто клеят к номеру: "11мкр", "66квартал"
  "микрорайон", "микр", "мкрн", "мкр", "mkr"
];

// Слова-ориентиры: после цифры допустимо любое продолжение слова («5аптека», «12магазин»).
const LANDMARK_PREFIXES = [
  "магазин", "дүкен", "аптек", "кафе", "ресторан", "рынок", "остановк", "почта", "больниц",
  "поликлиник", "возле", "около", "рядом", "напротив", "qazpost", "kazpost"
];

// Сокращения, после которых точку/пробел нужно привести к виду «ул. Абая»: "Ул .Курильская", "г.Алматы".
const ABBREVIATIONS = [
  "ул", "пр-т", "просп", "пр", "пер", "пл", "бул", "наб", "мкрн", "мкр", "микр",
  "обл", "р-н", "ш", "пос", "г", "д", "кв", "эт", "көш"
];

const alternation = words => [...words].sort((a, b) => b.length - a.length)
  .map(word => word.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")).join("|");

const KEYWORD = alternation(DETAIL_KEYWORDS);
const LANDMARK = alternation(LANDMARK_PREFIXES);
const ABBREVIATION = alternation(ABBREVIATIONS);

const RULES = [
  // 1. «дом4», «кв191», «подъезд№2»: ключевое слово + число. Слева не должно быть буквы, иначе это
  //    конец другого слова («Абаякв34» не трогаем — не знаем, где граница).
  {
    name: "keyword+number",
    pattern: new RegExp(`(?<!${U})(${KEYWORD})(?=[№#]?\\d)`, "giu")
  },
  // 2. «12дом», «69квартира», «4подьезд», «9этаж»: число + ключевое слово целиком (дальше не буква).
  {
    name: "number+keyword",
    pattern: new RegExp(`(\\d)(?=(?:${KEYWORD})(?!${U}))`, "giu")
  },
  // 3. «5магазин», «12аптека»: число + слово-ориентир (допускаем продолжение слова).
  {
    name: "number+landmark",
    pattern: new RegExp(`(\\d)(?=(?:${LANDMARK}))`, "giu")
  },
  // 4. «Абая12», «Назарбаева8», «Астана12»: слово (≥2 букв) + число.
  {
    name: "word+number",
    pattern: new RegExp(`(${U}{2})(?=\\d)`, "giu")
  },
  // 5. Сокращение + точка слитно со словом/числом, либо пробел перед точкой: "Ул .Курильская", "г.Алматы", "кв.191".
  {
    name: "abbreviation",
    pattern: new RegExp(`(?<![${U}\\d])(${ABBREVIATION})\\s*\\.\\s*(?=[${U}\\d])`, "giu"),
    suffix: ". "
  },
  // 6. Запятая/точка с запятой без пробела: "Астана,Абая".
  {
    name: "comma",
    pattern: /([,;])(?=[^\s\d,;])/gu
  }
];

/**
 * Разделяет склеенные слова, буквы и числа на границах шаблонов.
 *
 * @param {string} input строка адреса (уже без невидимых символов)
 * @returns {{ text: string, changed: boolean, applied: Record<string, number> }}
 *          text — нормализованная строка; applied — сколько раз сработало каждое правило
 *          (для отладки, тестов и экрана ручной правки).
 */
export function splitGluedTokens(input) {
  const source = String(input ?? "");
  const applied = {};
  let text = source;

  // Каждое правило захватывает «голову» (группа 1) и дописывает после неё suffix (по умолчанию — пробел).
  for (const rule of RULES) {
    text = text.replace(rule.pattern, (_match, head) => {
      applied[rule.name] = (applied[rule.name] ?? 0) + 1;
      return head + (rule.suffix ?? " ");
    });
  }

  text = text.replace(/\s+/gu, " ").trim();
  return { text, changed: text !== source.replace(/\s+/gu, " ").trim(), applied };
}
